import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = dirname(fileURLToPath(import.meta.url));
const sourcePath = join(root, "compression-dictionaries.json");
const compressPath = join(root, "src", "compress.ts");
const outputPath = join(root, "src", "compression-dictionaries.ts");
const dictionaryNames = ["tld", "sld", "domain", "path"];
const topologyAlphabet = "ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789-_";
const dictionaryImport = `import {
  domainDecode,
  domainEncode,
  pathDecode,
  pathEncode,
  sldDecode,
  sldEncode,
  sldList,
  tldDecode,
  tldEncode
} from "./compression-dictionaries.js";`;

function readDictionaries() {
  if (existsSync(sourcePath)) {
    return JSON.parse(readFileSync(sourcePath, "utf8"));
  }

  const compressSource = readFileSync(compressPath, "utf8");
  const dictionaries = {};

  for (const name of dictionaryNames) {
    const match = compressSource.match(
      new RegExp(`const ${name}Encode: Record<string, string> = (\\{.*?\\});`)
    );
    if (!match) throw new Error(`Could not find ${name}Encode in src/compress.ts`);
    dictionaries[name] = JSON.parse(match[1]);
  }

  writeFileSync(sourcePath, `${JSON.stringify(dictionaries)}\n`);
  return dictionaries;
}

function packTopology(bits) {
  let packed = "";
  for (let offset = 0; offset < bits.length; offset += 6) {
    const chunk = bits.slice(offset, offset + 6).padEnd(6, "0");
    packed += topologyAlphabet[Number.parseInt(chunk, 2)];
  }
  return packed;
}

function packDictionary(dictionary) {
  const rootNode = {};

  for (const [symbol, bits] of Object.entries(dictionary)) {
    let node = rootNode;
    for (const bit of bits) {
      node[bit] ??= {};
      node = node[bit];
    }
    if (node.symbol !== undefined) throw new Error(`Duplicate Huffman code: ${bits}`);
    node.symbol = symbol;
  }

  let topology = "";
  const symbols = [];

  function visit(node, bits) {
    if (node.symbol !== undefined) {
      if (node["0"] || node["1"]) throw new Error(`Huffman prefix collision at ${bits}`);
      topology += "1";
      symbols.push(node.symbol);
      return;
    }
    if (!node["0"] || !node["1"]) throw new Error(`Incomplete Huffman tree at ${bits}`);
    topology += "0";
    visit(node["0"], `${bits}0`);
    visit(node["1"], `${bits}1`);
  }

  visit(rootNode, "");

  if (symbols.some((symbol) => symbol.includes("|"))) {
    throw new Error("Packed dictionary symbol contains reserved separator");
  }

  return {
    topology: packTopology(topology),
    topologyBitLength: topology.length,
    symbols: symbols.join("|")
  };
}

const dictionaries = readDictionaries();
const packed = Object.fromEntries(
  dictionaryNames.map((name) => [name, packDictionary(dictionaries[name])])
);

const constants = dictionaryNames
  .map((name) => {
    const dictionary = packed[name];
    return `const ${name}Dictionary = unpackDictionary(${JSON.stringify(dictionary.topology)}, ${dictionary.topologyBitLength}, ${JSON.stringify(dictionary.symbols)});`;
  })
  .join("\n");

const output = `// Generated by generate-dictionaries.mjs. Do not edit directly.
export interface HuffmanDictionary {
  encode: Record<string, string>;
  decode: Record<string, string>;
}

const topologyAlphabet = ${JSON.stringify(topologyAlphabet)};

function unpackDictionary (
  packedTopology: string,
  topologyBitLength: number,
  packedSymbols: string
): HuffmanDictionary {
  const symbols = packedSymbols.split("|");
  const encode: Record<string, string> = {};
  const decode: Record<string, string> = {};
  let topologyOffset = 0;
  let symbolOffset = 0;

  function readNode (bits: string): void {
    if (topologyOffset >= topologyBitLength) {
      throw new Error("Invalid packed Huffman tree");
    }
    const packedValue = topologyAlphabet.indexOf(packedTopology[Math.floor(topologyOffset / 6)]);
    const isLeaf = (packedValue >> (5 - topologyOffset % 6)) & 1;
    topologyOffset ++;

    if (isLeaf) {
      const symbol = symbols[symbolOffset ++];
      encode[symbol] = bits;
      decode[bits] = symbol;
      return;
    }

    readNode(\`\${bits}0\`);
    readNode(\`\${bits}1\`);
  }

  readNode("");
  if (topologyOffset !== topologyBitLength || symbolOffset !== symbols.length) {
    throw new Error("Invalid packed Huffman dictionary");
  }
  return { encode, decode };
}

${constants}

export const tldEncode = tldDictionary.encode;
export const tldDecode = tldDictionary.decode;
export const sldEncode = sldDictionary.encode;
export const sldDecode = sldDictionary.decode;
export const domainEncode = domainDictionary.encode;
export const domainDecode = domainDictionary.decode;
export const pathEncode = pathDictionary.encode;
export const pathDecode = pathDictionary.decode;
export const sldList = Object.keys(sldEncode).sort((a, b) => b.length - a.length);
`;

writeFileSync(outputPath, output);

const compressSource = readFileSync(compressPath, "utf8");
if (compressSource.includes("const tldEncode:")) {
  const dictionaryBlockStart = compressSource.indexOf("const tldEncode:");
  const nextSection = compressSource.indexOf("The following two functions", dictionaryBlockStart);
  const dictionaryBlockEnd = compressSource.lastIndexOf("/**", nextSection);
  if (nextSection < 0 || dictionaryBlockEnd < 0) {
    throw new Error("Could not locate end of inline dictionaries");
  }

  const migratedSource = `${dictionaryImport}\n\n${compressSource.slice(0, dictionaryBlockStart)}${compressSource.slice(dictionaryBlockEnd)}`;
  writeFileSync(compressPath, migratedSource);
}
